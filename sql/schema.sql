CREATE TABLE {prefix}STOCK (
    CPRODUCTO NUMBER(9,0) PRIMARY KEY CHECK (CPRODUCTO > 0),
    CANTIDAD NUMBER(9,0) NOT NULL CHECK (CANTIDAD >= 0)
);
CREATE TABLE {prefix}PEDIDO (
    CPEDIDO NUMBER(9,0) PRIMARY KEY CHECK (CPEDIDO > 0),
    CCLIENTE NUMBER(9,0) NOT NULL CHECK (CCLIENTE > 0),
    FECHA_PEDIDO DATE NOT NULL
);
CREATE TABLE {prefix}DETALLE_PEDIDO (
    CPEDIDO NUMBER(9,0),
    CPRODUCTO NUMBER(9,0),
    CANTIDAD NUMBER(9,0) NOT NULL CHECK (CANTIDAD > 0),
    PRIMARY KEY (CPEDIDO, CPRODUCTO),
    FOREIGN KEY (CPEDIDO) REFERENCES {prefix}PEDIDO(CPEDIDO),
    FOREIGN KEY (CPRODUCTO) REFERENCES {prefix}STOCK(CPRODUCTO)
);
